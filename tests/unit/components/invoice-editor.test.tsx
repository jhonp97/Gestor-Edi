import { describe, it, expect, vi, beforeEach, afterEach } from 'vitest'
import { render, screen, fireEvent, waitFor, cleanup } from '@testing-library/react'
import { InvoiceEditor } from '@/components/facturas/invoice-editor'
import { createInvoiceDraft } from '@/lib/invoice'
import { draftStorageKey, emptyDraftStore, saveDraft, writeDraftStore, readDraftStore, MAX_TRANSFER_BYTES } from '@/lib/invoice-drafts'
const mocks = vi.hoisted(() => ({ fetch: vi.fn() }))
vi.mock('@/hooks/use-api', () => ({ apiFetch: mocks.fetch }))
const account = { orgId: 'org', userId: 'user' }
const validInvoice = () => ({ ...createInvoiceDraft(), number: 13, lines: [{ description: 'Transporte', quantity: '25', unitPrice: '185' }, { description: 'Transporte 2', quantity: '28', unitPrice: '185' }, { description: 'Transporte 3', quantity: '5', unitPrice: '185' }, { description: 'Extra', quantity: '5', unitPrice: '30' }] })
async function openSaved() {
  writeDraftStore(localStorage, account, saveDraft(emptyDraftStore(), validInvoice()))
  render(<InvoiceEditor {...account} />)
  fireEvent.click(await screen.findByRole('button', { name: 'Abrir factura 13' }))
}
beforeEach(() => {
  localStorage.clear()
  mocks.fetch.mockReset()
  vi.stubGlobal('confirm', vi.fn(() => true))
  Object.defineProperty(URL, 'createObjectURL', { configurable: true, value: vi.fn(() => 'blob:test') })
  Object.defineProperty(URL, 'revokeObjectURL', { configurable: true, value: vi.fn() })
  vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(() => {})
})
afterEach(() => { cleanup(); vi.restoreAllMocks(); vi.unstubAllGlobals() })
const input = (name: string, value: string) => fireEvent.change(screen.getByLabelText(name), { target: { value } })
describe('Editor de facturas', () => {
  it('presenta valores predeterminados y permite editar fecha, número y ambas partes', async () => {
    render(<InvoiceEditor {...account} />)
    expect(screen.getByLabelText('Descuento (%)')).toHaveValue('5.00')
    expect(screen.getByLabelText('IVA (%)')).toHaveValue('21.00')
    expect(screen.getByLabelText('Fecha')).toHaveValue(createInvoiceDraft().date)
    input('Número de factura', '25')
    input('Fecha', '2026-09-30')
    input('Emisor · Nombre', 'Empresa editada')
    input('Destinatario · Nombre', 'Cliente editado')
    expect(screen.getByLabelText('Emisor · Nombre')).toHaveValue('Empresa editada')
    expect(screen.getByLabelText('Destinatario · Nombre')).toHaveValue('Cliente editado')
    expect(screen.getByText(/no se comparten entre dispositivos/i)).toBeInTheDocument()
  })
  it('reproduce los totales de referencia y actualiza conceptos', async () => {
    await openSaved()
    expect(screen.getByTestId('total')).toHaveTextContent('12.506,56')
    expect(screen.getByTestId('subtotal')).toHaveTextContent('10.880,00')
    fireEvent.click(screen.getByRole('button', { name: 'Añadir concepto' }))
    expect(screen.getAllByLabelText(/Descripción \d/)).toHaveLength(5)
    fireEvent.click(screen.getByRole('button', { name: 'Eliminar concepto 5' }))
    expect(screen.getAllByLabelText(/Descripción \d/)).toHaveLength(4)
    input('Descuento (%)', '0')
    expect(screen.getByTestId('total')).toHaveTextContent('13.164,80')
  })
  it('guarda explícitamente, reabre el número y confirma eliminación', async () => {
    await openSaved()
    input('Descripción 1', 'Cambio')
    fireEvent.click(screen.getByRole('button', { name: 'Guardar borrador' }))
    cleanup()
    render(<InvoiceEditor {...account} />)
    fireEvent.click(await screen.findByRole('button', { name: 'Abrir factura 13' }))
    expect(screen.getByLabelText('Número de factura')).toHaveValue('13')
    expect(screen.getByLabelText('Descripción 1')).toHaveValue('Cambio')
    fireEvent.click(screen.getByRole('button', { name: 'Eliminar factura 13' }))
    expect(confirm).toHaveBeenCalled()
    expect(screen.queryByRole('button', { name: 'Abrir factura 13' })).not.toBeInTheDocument()
  })
  it('no filtra el borrador al cambiar usuario u organización', async () => {
    await openSaved()
    cleanup()
    const view = render(<InvoiceEditor orgId="org" userId="other" />)
    expect(screen.getByLabelText('Número de factura')).toHaveValue('1')
    expect(screen.queryByRole('button', { name: 'Abrir factura 13' })).not.toBeInTheDocument()
    view.rerender(<InvoiceEditor orgId="other" userId="user" />)
    expect(screen.getByLabelText('Número de factura')).toHaveValue('1')
  })
  it('muestra validación sin consumir número ni enviar PDF', async () => {
    await openSaved()
    input('Cantidad 1', '-1')
    fireEvent.click(screen.getByRole('button', { name: 'Descargar PDF' }))
    expect(screen.getByRole('alert')).toBeInTheDocument()
    expect(mocks.fetch).not.toHaveBeenCalled()
    expect(readDraftStore(localStorage, account).nextNumber).toBe(1)
  })
  it('no avanza al rechazar HTTP y permite PDF con almacenamiento no disponible', async () => {
    await openSaved()
    mocks.fetch.mockResolvedValueOnce(new Response('', { status: 400 }))
    fireEvent.click(screen.getByRole('button', { name: 'Descargar PDF' }))
    await waitFor(() => expect(screen.getByRole('alert')).toHaveTextContent(/descargar/i))
    expect(readDraftStore(localStorage, account).nextNumber).toBe(1)
    vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new Error('quota') })
    mocks.fetch.mockResolvedValueOnce(new Response('%PDF-1.7', { headers: { 'Content-Type': 'application/pdf' } }))
    fireEvent.click(screen.getByRole('button', { name: 'Descargar PDF' }))
    await waitFor(() => expect(URL.revokeObjectURL).toHaveBeenCalled())
    expect(screen.getByRole('alert')).toHaveTextContent(/almacenamiento/i)
  })
  it('deshabilita durante descarga, avanza solo al recibir PDF y no consume al repetir', async () => {
    await openSaved()
    let resolve!: (response: Response) => void
    mocks.fetch.mockReturnValueOnce(new Promise<Response>(done => { resolve = done }))
    fireEvent.click(screen.getByRole('button', { name: 'Descargar PDF' }))
    expect(screen.getByRole('button', { name: 'Descargando…' })).toBeDisabled()
    resolve(new Response('%PDF-1.7', { headers: { 'Content-Type': 'application/pdf' } }))
    await waitFor(() => expect(readDraftStore(localStorage, account).nextNumber).toBe(14))
    mocks.fetch.mockResolvedValueOnce(new Response('%PDF-1.7', { headers: { 'Content-Type': 'application/pdf' } }))
    fireEvent.click(screen.getByRole('button', { name: 'Descargar PDF' }))
    await waitFor(() => expect(mocks.fetch).toHaveBeenCalledTimes(2))
    expect(readDraftStore(localStorage, account).nextNumber).toBe(14)
    fireEvent.click(screen.getByRole('button', { name: 'Nueva factura' }))
    expect(screen.getByLabelText('Número de factura')).toHaveValue('14')
  })
  it('exporta JSON y advierte sobre información personal', async () => {
    await openSaved()
    fireEvent.click(screen.getByRole('button', { name: 'Exportar JSON' }))
    expect(URL.createObjectURL).toHaveBeenCalled()
    expect(screen.getByText(/datos personales/i)).toBeInTheDocument()
  })
  it.each(['{', JSON.stringify({ version: 1, invoice: { ...validInvoice(), unknown: true } }), 'x'.repeat(MAX_TRANSFER_BYTES + 1)])('rechaza transferencia sin alterar borrador ni almacenamiento', async text => {
    await openSaved()
    const previous = localStorage.getItem(draftStorageKey(account))
    fireEvent.change(screen.getByLabelText('Importar JSON'), { target: { files: [new File([text], 'invoice.json')] } })
    await waitFor(() => expect(screen.getByRole('alert')).toBeInTheDocument())
    expect(screen.getByLabelText('Número de factura')).toHaveValue('13')
    expect(localStorage.getItem(draftStorageKey(account))).toBe(previous)
  })
  it('importa sin sobrescribir otro borrador y muestra duplicados locales', async () => {
    await openSaved()
    const file = new File([JSON.stringify({ version: 1, invoice: validInvoice() })], 'invoice.json')
    fireEvent.change(screen.getByLabelText('Importar JSON'), { target: { files: [file] } })
    await waitFor(() => expect(screen.getByRole('status')).toHaveTextContent(/importado/i))
    expect(readDraftStore(localStorage, account).drafts).toHaveLength(2)
    expect(screen.getByText(/Número repetido/i)).toBeInTheDocument()
  })
})
